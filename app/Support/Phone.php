<?php

namespace App\Support;

class Phone
{
    /**
     * توحيد صيغة رقم الهاتف قبل التخزين أو المطابقة:
     * - تحويل الأرقام العربية (٠-٩) والفارسية (۰-۹) إلى إنجليزية.
     * - إزالة المسافات والشرطات والأقواس.
     */
    public static function normalize(?string $raw): ?string
    {
        if ($raw === null) {
            return null;
        }

        $ascii = strtr($raw, [
            '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
            '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
            '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
            '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9',
        ]);

        // إزالة المسافات والفواصل الشائعة (تبقى + والأرقام)
        return preg_replace('/[\s\-()]/u', '', trim($ascii));
    }
}
